import { isDeepStrictEqual } from 'node:util';
import { cpSync, copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const project = fileURLToPath(new URL('..', import.meta.url));
const base = path.join(project, 'outputs');
const target = path.join(base, 'youyu-server');
const relative = path.relative(base, target);
if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) throw Error('Invalid staging directory');
const release = JSON.parse(readFileSync(path.join(project, 'public/downloads/release.json'), 'utf8'));
if (!existsSync(path.join(project, 'public/downloads', release.filename))) throw Error('Build the signed Android release first');
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
for (const dir of ['app', 'components', 'hooks', 'lib', 'public', 'vendor']) {
  cpSync(path.join(project, dir), path.join(target, dir), { recursive: true, filter: input => !input.endsWith(`${path.sep}chatgpt-auth.ts`) });
}
cpSync(path.join(project, 'deploy/selfhost/overlay'), target, { recursive: true });
cpSync(path.join(project, 'deploy/ubuntu'), path.join(target, 'ubuntu'), { recursive: true });
copyFileSync(path.join(project, 'postcss.config.mjs'), path.join(target, 'postcss.config.mjs'));
copyFileSync(path.join(project, '.npmrc'), path.join(target, '.npmrc'));
const pkg = JSON.parse(readFileSync(path.join(project, 'package.json'), 'utf8'));
pkg.name = 'youyu-selfhost'; pkg.version = release.versionName;
pkg.engines = { node: '>=24 <25' };
pkg.scripts = { dev: 'next dev --webpack --hostname 127.0.0.1', build: 'next build --webpack', start: 'next start --hostname 127.0.0.1 --port 3000', test: 'node --test tests/*.test.mjs' };
writeFileSync(path.join(target, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');
const lock = JSON.parse(readFileSync(path.join(project, 'deploy/selfhost/package-lock.json'), 'utf8'));
if (!isDeepStrictEqual(lock.packages[''].dependencies, pkg.dependencies) || !isDeepStrictEqual(lock.packages[''].devDependencies, pkg.devDependencies)) throw Error('Self-host lock is out of sync. Refresh deploy/selfhost/package-lock.json with npm install --package-lock-only before packaging.');
lock.name = pkg.name; lock.version = pkg.version;
Object.assign(lock.packages[''], { name: pkg.name, version: pkg.version, engines: pkg.engines });
writeFileSync(path.join(target, 'package-lock.json'), JSON.stringify(lock, null, 2) + '\n');
const config = JSON.parse(readFileSync(path.join(project, 'tsconfig.json'), 'utf8'));
config.compilerOptions.types = ['node'];
config.exclude = ['node_modules', 'tests'];
writeFileSync(path.join(target, 'tsconfig.json'), JSON.stringify(config, null, 2) + '\n');
writeFileSync(path.join(target, 'next-env.d.ts'), '/// <reference types="next" />\n/// <reference types="next/image-types/global" />\n');
writeFileSync(path.join(target, 'next.config.mjs'), `export default { outputFileTracingRoot: process.cwd(), experimental: { cpus: 2 }, poweredByHeader: false, async headers() { return [{ source: '/:path*', headers: [{key:'X-Content-Type-Options',value:'nosniff'},{key:'X-Frame-Options',value:'DENY'},{key:'Referrer-Policy',value:'strict-origin-when-cross-origin'}] }]; } };\n`);
writeFileSync(path.join(target, '.env.production'), 'YOUYU_ORIGIN=https://youyuapp.com.cn\nYOUYU_REGISTRATION=open\nYOUYU_DATA_DIR=/var/lib/youyu\nYOUYU_ICP_NUMBER=冀ICP备2025113362号-2\nNEXT_TELEMETRY_DISABLED=1\n');
writeFileSync(path.join(target, '.gitignore'), 'node_modules/\n.next/\ndata/\n.env.local\n*.sqlite*\n');
const appFile = path.join(target, 'app/ledger-app.tsx');
let app = readFileSync(appFile, 'utf8');
const loginLink = '/signin-with-chatgpt?return_to=/';
if (!app.includes(loginLink) || !app.includes('<InstallAppCard/>')) throw Error('Ledger UI changed; review self-host substitutions');
app = app.replaceAll(loginLink, '/login').replace('<InstallAppCard/>', '<><InstallAppCard/><SessionSettings/></>');
app = app.replace(/^\s*['"]use client['"];?\s*/, '');
writeFileSync(appFile, "'use client';\nimport SessionSettings from './session-settings';\n" + app);
const layoutFile = path.join(target, 'app/layout.tsx');
writeFileSync(layoutFile, "export const dynamic = 'force-dynamic';\n" + readFileSync(layoutFile, 'utf8'));
const introFile = path.join(target, 'app/intro/page.tsx');
let intro = readFileSync(introFile, 'utf8').replaceAll('href="/"', 'href="/app"');
intro = "import IcpFooter from '../icp-footer';\n" + intro;
intro = intro.replace('<footer className="site-footer">', '<footer className="site-footer"><IcpFooter />');
intro = intro.replace('export default function IntroPage()', "export const dynamic = 'force-dynamic';\nexport default function IntroPage()");
writeFileSync(introFile, intro);
const manifestFile = path.join(target, 'public/manifest.webmanifest');
const manifest = JSON.parse(readFileSync(manifestFile, 'utf8')); manifest.id = '/app'; manifest.start_url = '/app';
writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
mkdirSync(path.join(target, 'tests'), { recursive: true });
const testFile = readFileSync(path.join(project, 'deploy/selfhost/tests/runtime.test.mjs'), 'utf8').replaceAll('../overlay/runtime/', '../runtime/');
writeFileSync(path.join(target, 'tests/runtime.test.mjs'), testFile);
copyFileSync(path.join(project, 'deploy/README.md'), path.join(target, '部署说明.md'));
console.log(JSON.stringify({ target, domain: 'youyuapp.com.cn', icp: '冀ICP备2025113362号-2', registration: 'open', android: release.versionName }, null, 2));
